VOL = re.compile(r"(\d+(?:[.,]\d+)?)\s?(мл|ml|л|l|кг|kg|г|гр|g)\b", re.I)

def vol(n):
    m = VOL.search(n.replace("ML", "мл").replace("КГ", "кг"))
    if not m: return None
    v, u = m.group(1).replace(".", ","), m.group(2).lower()
    u = {"ml": "мл", "l": "л", "kg": "кг", "гр": "г", "g": "г"}.get(u, u)
    return f"{v} {u}"

def color(n):
    l = n.lower()
    for k, v in COL:
        if re.search(r"(?<![а-я])" + k, l): return v
    return None

def dims_cm(n):
    m = re.search(r"(\d+(?:[.,]\d+)?)\s*[*×xх]\s*(\d+(?:[.,]\d+)?)(?:\s*[*×xх]\s*(\d+(?:[.,]\d+)?))?\s*(см|мм)?", n)
    if not m: return None
    parts = [g.replace(".", ",") for g in m.groups()[:3] if g]
    return "×".join(parts) + " " + (m.group(4) or "см")

def clean_model(n, drop):
    s = re.sub(r"^" + drop + r"\s*", "", n, flags=re.I)
    return s.strip()

