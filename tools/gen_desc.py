       ("желт", "жёлтый"), ("коричн", "коричневый"), ("беж", "бежевый"), ("розов", "розовый"), ("оранж", "оранжевый"), ("серебр", "серебристый"),
       ("золот", "золотистый"), ("бронз", "бронзовый"), ("вишн", "вишнёвый"), ("орех", "орех"), ("ваниль", "ванильный"), ("персик", "персиковый"),
