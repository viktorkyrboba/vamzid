LAT = set("ABCEHKMOPTXYabcehkmoptxy")
CYR2LAT = dict(zip("АВЕКМНОРСТХУавекмнорсху", "ABEKMHOPCTXYabekmhopcxy"))
UN = {"ММ":"мм","СМ":"см","КГ":"кг","МЛ":"мл","Л":"л","Г":"г","ШТ":"шт","М":"м"}
def nice(name):
    _u=len(re.findall(r"[А-ЯЁ]",name)); _l=len(re.findall(r"[а-яё]",name)); caps = _u>0 and _u>=1.5*_l
    s = name.strip()
    s = re.sub(r"\s+", " ", s)
    s = re.sub(r"Д/(?=\S)", "для ", s)
    for a, b in [("ДМАССАЖА","для массажа"),("ДПИЛАТЕСА","для пилатеса"),("ДУДАЛЕНИЯ","для удаления"),("МАШИНКА ДСТР","МАШИНКА для стрижки"),
                 ("ЩИПЦЫ ДВЫПР.","ЩИПЦЫ для выпрямления "),("ДСТР","для стрижки"),("ДУКЛ","для укладки"),("К-КА ","Краска "),("В/Э ","Водоэмульсионная краска "),
                 ("РЕШЕТКА ПЛ.ДОТЖИМА","РЕШЕТКА пластиковая для отжима"),("ВАГОНКА ПЛ ","ВАГОНКА пластиковая ")]:
        s = s.replace(a, b)
    s = re.sub(r"\bД\b", "для", s)
    s = re.sub(r"(?<=\d)(ММ|СМ|КГ|МЛ|Л|Г|ШТ)(?![А-Яа-яA-Za-z])", lambda m: " " + UN[m.group(1)], s)
    toks = []
    for t in s.split(" "):
        if re.search(r"[A-Za-z]", t) and re.search(r"[А-Яа-яЁё]", t) and re.search(r"\d", t):
            t = "".join(CYR2LAT.get(c, c) for c in t)       # кириллица внутри модели -> латиница
        toks.append(t)
    s = " ".join(toks)
    if caps:                                                 # ВСЁ ЗАГЛАВНЫМИ -> нормальный регистр
        out = []
        for t in s.split(" "):
            if re.search(r"[A-Za-z]", t) or len(t) == 1: out.append(t)
            else: out.append(re.sub(r"[А-ЯЁ]+", lambda m: m.group(0).lower(), t))
        s = " ".join(out)
    s = s.strip()
    return s[0].upper() + s[1:]

def imgpath(r, idx, name):
    v = r.strip()
    if not v: return ""
    if v[0] == "=":
        fo, _, ex = v[1:].partition("|")
        fo = fo or CF.get(idx, "")
        return f"TOVARS/{fo}/{name}/1.{ex or 'png'}"
    return v

def main():
    s = open("src/index.html", encoding="utf-8").read()
    i0 = s.index("const PRODUCTS=[") + len("const PRODUCTS=[")
    i1 = s.index("\n];", i0)
    have = set(re.findall(r'code:"(\d+)"', s[i0:i1]))
    rows = [l.split("|") for l in open("tools/raw/all.txt", encoding="utf-8").read().split("\n") if l.strip()]
    res, mn, skip = [], {}, 0
    for code, name, price, idx, im in [(r[0], r[1], r[2], int(r[3]), "|".join(r[4:]) if len(r) > 4 else "") for r in rows]:
        if code in have: skip += 1; continue
        have.add(code)
        rub, g, x = classify(idx, name)
        mn.setdefault(rub, {}).setdefault(g, [])
        if x not in mn[rub][g]: mn[rub][g].append(x)
        p = imgpath(im, idx, name)
        parts = [f"n:{json.dumps(nice(name), ensure_ascii=False)}", f"r:{json.dumps(rub, ensure_ascii=False)}", f"g:{json.dumps(g, ensure_ascii=False)}",
                 f"x:{json.dumps(x, ensure_ascii=False)}", f"p:{int(price) if price.isdigit() else price}", 'img:""', f'code:"{code}"']
        if p: parts.append(f"im:{json.dumps(p, ensure_ascii=False)}")
        res.append("{" + ",".join(parts) + "}")
    # MENU
    m0 = s.index("const MENU=") + len("const MENU=")
    m1 = s.index(";\n", m0)
    menu = json.loads(s[m0:m1])
    for rub, gs in mn.items():
        R = next((r for r in menu if r[0] == rub), None)
        if not R: R = [rub, []]; menu.append(R)
        for g, xs in gs.items():
            G = next((q for q in R[1] if q[0] == g), None)
            if not G: G = [g, []]; R[1].append(G)
            for x in xs:
                if x not in G[1]: G[1].append(x)
    s = s[:i1] + ",\n" + ",\n".join(res) + s[i1:]
    s = s[:m0] + json.dumps(menu, ensure_ascii=False, separators=(",", ":")) + s[m1:]
    hook = 'PRODUCTS.forEach(p=>{if(p.im)p.img2="https://vamzid.md/image/catalog/"+p.im.split("/").map(encodeURIComponent).join("/")});'
    if hook not in s:
        e = s.index("\n];", s.index("const PRODUCTS=[")) + 3
        s = s[:e] + "\n" + hook + s[e:]
    open("src/index.html", "w", encoding="utf-8").write(s)
    print("добавлено", len(res), "пропущено (уже есть)", skip)
    for rub, gs in mn.items(): print(rub, {g: xs for g, xs in gs.items()})
main()
